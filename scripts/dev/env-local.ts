/**
 * Writes .env.supabase.local for running the app against the LOCAL Supabase
 * stack (`pnpm db:start` first). Uses only the well-known local development
 * keys printed by `supabase status`; never production credentials.
 * A suppression pepper is generated once and kept on re-runs.
 *
 * Usage: pnpm env:local   then   pnpm dev:supabase
 */
import { execSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "..");
const target = join(root, ".env.supabase.local");

const status = execSync("npx supabase status -o env", { cwd: root, encoding: "utf8" });
const values = Object.fromEntries(
  status
    .split(/\r?\n/)
    .map((line) => /^([A-Z_]+)="?(.*?)"?$/.exec(line.trim()))
    .filter((m): m is RegExpExecArray => !!m)
    .map((m) => [m[1], m[2]]),
);

const apiUrl = values.API_URL;
if (!apiUrl || !/^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?$/.test(apiUrl)) {
  console.error("Local Supabase is not running (or not on localhost). Start it with `pnpm db:start`.");
  process.exit(1);
}

const existingPepper = existsSync(target)
  ? /^SUPPRESSION_PEPPER=(.+)$/m.exec(readFileSync(target, "utf8"))?.[1]
  : undefined;

const lines = [
  "# Generated by `pnpm env:local` for the LOCAL Supabase stack. Do not commit.",
  "APP_ENV=local",
  "DATA_SOURCE=supabase",
  "NEXT_PUBLIC_APP_URL=http://localhost:3001",
  "OPT_OUT_BASE_URL=localhost:3001/o",
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${values.ANON_KEY}`,
  `SUPABASE_SERVICE_ROLE_KEY=${values.SERVICE_ROLE_KEY}`,
  `SUPABASE_DB_URL=${values.DB_URL}`,
  "EMAIL_PROVIDER=smtp",
  "SMTP_URL=smtp://127.0.0.1:54325",
  `SUPPRESSION_PEPPER=${existingPepper ?? randomBytes(32).toString("base64")}`,
  "SMS_PROVIDER=mock",
  "AI_PROVIDER=mock",
  "",
];
writeFileSync(target, lines.join("\n"));
console.log(`Wrote ${target}`);
console.log("Mailpit (local inbox): http://127.0.0.1:54324");
